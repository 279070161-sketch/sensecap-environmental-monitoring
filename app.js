  // Fit dual images: compute height H so both images together exactly fill column width
  // H × (ratio1 + ratio2) + gap = wrapWidth  =>  H = (wrapWidth - gap) / (ratio1 + ratio2)
  function fitDualImages() {
    var wrap = document.querySelector('.sensecraft-dual-image-wrap');
    if (!wrap) return;
    var imgs = Array.prototype.slice.call(wrap.querySelectorAll('img'));
    if (imgs.length < 2) return;

    function compute() {
      for (var i = 0; i < imgs.length; i++) {
        if (!imgs[i].naturalWidth) return; // not loaded yet
      }
      var wrapWidth = wrap.clientWidth;
      if (!wrapWidth) return;

      var gap = 16; // must match CSS gap
      var totalRatio = imgs.reduce(function (sum, img) {
        return sum + img.naturalWidth / img.naturalHeight;
      }, 0);

      var H = (wrapWidth - gap) / totalRatio;
      H = Math.max(160, Math.min(480, H)); // min 160px, max 480px

      imgs.forEach(function (img) {
        img.style.height = H + 'px';
        img.style.width = 'auto';
      });
    }

    // Trigger after each image loads
    var loaded = 0;
    imgs.forEach(function (img) {
      if (img.complete && img.naturalWidth) {
        loaded++;
        if (loaded >= imgs.length) compute();
      } else {
        img.addEventListener('load', function () {
          loaded++;
          if (loaded >= imgs.length) compute();
        });
      }
    });

    // Re-compute on resize
    var resizeTimer;
    window.addEventListener('resize', function () {
      clearTimeout(resizeTimer);
      resizeTimer = setTimeout(compute, 80);
    });
  }
  fitDualImages();

  // Animated Count-Up for Stat Items
  function initCountUpStats() {
    var statItems = document.querySelectorAll(".stat-item");
    if (!statItems.length) return;

    var observer = new IntersectionObserver(function (entries) {
      entries.forEach(function (entry) {
        if (entry.isIntersecting) {
          var strong = entry.target.querySelector("strong");
          if (!strong || strong.dataset.animated) return;
          strong.dataset.animated = "true";
          entry.target.classList.add("is-visible");

          var rawText = strong.textContent.trim();
          var match = rawText.match(/^(\d+)(\+?)$/);
          if (!match) return;

          var targetVal = parseInt(match[1], 10);
          var suffix = match[2] || "";
          var duration = 1600;
          var startTime = null;

          function step(timestamp) {
            if (!startTime) startTime = timestamp;
            var progress = Math.min((timestamp - startTime) / duration, 1);
            var easeProgress = 1 - Math.pow(1 - progress, 3);
            var currentVal = Math.floor(easeProgress * targetVal);
            strong.textContent = currentVal + suffix;
            if (progress < 1) {
              requestAnimationFrame(step);
            } else {
              strong.textContent = targetVal + suffix;
            }
          }
          requestAnimationFrame(step);
        }
      });
    }, { threshold: 0.4 });

    statItems.forEach(function (item) { observer.observe(item); });
  }

  // Scroll Reveal Animation Engine
  function initScrollReveal() {
    // Select elements to reveal
    var targets = document.querySelectorAll([
      ".stat-item",
      ".feature-card",
      ".product-finder .selector-layout",
      ".deployments-heading",
      ".deployment-accordion-card",
      ".editorial-heading",
      ".editorial-card",
      ".sensecraft-row-card",
      ".contact-inner"
    ].join(","));

    if (!targets.length) return;

    // Add base reveal-on-scroll class and staggered delays to siblings
    targets.forEach(function (el) {
      el.classList.add("reveal-on-scroll");

      // Apply staggered delays for grid/flex sibling items
      var parent = el.parentElement;
      if (parent) {
        var siblings = Array.prototype.filter.call(parent.children, function (child) {
          return child.classList.contains("reveal-on-scroll") || child.matches(".feature-card, .stat-item, .deployment-accordion-card, .editorial-card");
        });
        var index = siblings.indexOf(el);
        if (index > 0) {
          var delayClass = "reveal-delay-" + Math.min(index, 5);
          el.classList.add(delayClass);
        }
      }
    });

    var observer = new IntersectionObserver(function (entries) {
      entries.forEach(function (entry) {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-revealed");
          // Unobserve once revealed for smooth performance
          observer.unobserve(entry.target);
        }
      });
    }, {
      threshold: 0.12,
      rootMargin: "0px 0px -40px 0px"
    });

    targets.forEach(function (el) {
      observer.observe(el);
    });
  }

  initCountUpStats();
  initScrollReveal();
