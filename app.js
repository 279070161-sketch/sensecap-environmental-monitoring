  function setupContactNeuralCanvas() {
    var canvas = document.getElementById("contact-neural-canvas");
    if (!canvas) return;

    var ctx = canvas.getContext("2d");
    var width = 0, height = 0;

    function resize() {
      var rect = canvas.getBoundingClientRect();
      width = canvas.width = rect.width;
      height = canvas.height = rect.height;
    }
    resize();
    window.addEventListener("resize", resize, { passive: true });

    var particles = [];
    var particleCount = 45;

    function Particle() {
      this.x = Math.random() * width;
      this.y = Math.random() * height;
      this.vx = (Math.random() - 0.5) * 0.7;
      this.vy = (Math.random() - 0.5) * 0.7;
      this.radius = Math.random() * 2.0 + 1.2;
      this.baseAlpha = Math.random() * 0.35 + 0.45;
    }

    Particle.prototype.update = function () {
      this.x += this.vx;
      this.y += this.vy;

      if (this.x < 0 || this.x > width) this.vx *= -1;
      if (this.y < 0 || this.y > height) this.vy *= -1;
    };

    Particle.prototype.draw = function () {
      ctx.beginPath();
      ctx.arc(this.x, this.y, this.radius, 0, Math.PI * 2);
      ctx.fillStyle = "rgba(141, 194, 31, " + this.baseAlpha + ")";
      ctx.shadowBlur = 8;
      ctx.shadowColor = "rgba(141, 194, 31, 0.6)";
      ctx.fill();
      ctx.shadowBlur = 0;
    };

    function initParticles() {
      particles = [];
      for (var i = 0; i < particleCount; i++) {
        particles.push(new Particle());
      }
    }

    function connectParticles() {
      var maxDist = 145;
      for (var i = 0; i < particles.length; i++) {
        for (var j = i + 1; j < particles.length; j++) {
          var dx = particles[i].x - particles[j].x;
          var dy = particles[i].y - particles[j].y;
          var dist = Math.sqrt(dx * dx + dy * dy);

          if (dist < maxDist) {
            var opacity = (1 - dist / maxDist) * 0.38;
            ctx.beginPath();
            ctx.strokeStyle = "rgba(141, 194, 31, " + opacity + ")";
            ctx.lineWidth = 0.9;
            ctx.moveTo(particles[i].x, particles[i].y);
            ctx.lineTo(particles[j].x, particles[j].y);
            ctx.stroke();
          }
        }
      }
    }

    function animate() {
      ctx.clearRect(0, 0, width, height);
      for (var i = 0; i < particles.length; i++) {
        particles[i].update();
        particles[i].draw();
      }
      connectParticles();
      requestAnimationFrame(animate);
    }

    initParticles();
    animate();
  }

